"""Render c1_prop5_certificate.json as a LaTeX table snippet (c1_prop5_table.tex)."""
import json
from pathlib import Path
H = Path(__file__).resolve().parent
c = json.loads((H/'c1_prop5_certificate.json').read_text())
def common(lo, hi):
    k = 0
    while k < min(len(lo), len(hi)) and lo[k] == hi[k]: k += 1
    return lo[:k]
rows = []
comp = c['t_star']['components']
for i in range(1, 6):
    a = next(r for r in comp if r['i'] == i and r['prep'] == 'beta=3')
    b = next(r for r in comp if r['i'] == i and r['prep'] == 'beta=4')
    rows.append('$%d$ & $%s$ & $%s\\ldots$ & $%s\\ldots$ & $%s$ & $%s$\\\\' % (
        i, a['pi'][:12], common(a['lo'], a['hi'])[:20], common(b['lo'], b['hi'])[:20], a['sign'],
        a['width'].replace('E-', '\\times10^{-') + '}'))
s = c['decimal_scan']; br = c['certified_brackets']
def sci(x, n=30):
    m, e = x.split('E'); return m[:n] + r'\times10^{' + str(int(e)) + '}'
lo = sci(c['t_star']['sign_quantity_lower']); hi = sci(c['t_star']['sign_quantity_upper'])
rob = c['robustness']
wmin = min(float(r['window'][0]) for r in rob); wmax = max(float(r['window'][1]) for r in rob)
tex = r"""%% C1: generated by c1_make_table.py from c1_prop5_certificate.json
\begin{table}[tb]
\centering\small
\caption{Rational interval certificate for Proposition~\ref{prop:TV} at $t_*=1047/100$ (uniformisation rate $2$, $101$ terms, $x=1047/50$, unnormalised tail bound $T<3.6\times10^{-27}$ against $B>10^{9}$). Shown are the digits common to both exact rational endpoints; the full endpoints are in \texttt{c1\_prop5\_certificate.json}. Signs refer to $p_i(t_*)-\pi_i$ and are identical for both preparations.}
\label{tab:prop5cert}
\begin{tabular}{cccccc}
\toprule
$i$ & $\pi_i$ & $p_{3,i}(t_*)$ & $p_{4,i}(t_*)$ & sign & width\\\midrule
%s
\midrule
\multicolumn{6}{p{.95\linewidth}}{$%s<\TV(p_3(t_*),\pi)-\TV(p_4(t_*),\pi)<%s$ (exact rational bounds)}\\
\multicolumn{6}{p{.95\linewidth}}{Certified signs of $\TV(p_3(t),\pi)-\TV(p_4(t),\pi)$: $t=10.46$: $-$;\ $t=10.47$: $+$;\ $t=10.48$: $-$.}\\
\multicolumn{6}{p{.95\linewidth}}{60-digit scan on $[0,60]$: crossings at $t_1=%s\ldots$, $t_2=%s\ldots$; no others.}\\
\bottomrule
\end{tabular}
\end{table}
""" % ('\n'.join(rows), lo, hi, s['crossings'][0][:16], s['crossings'][1][:16])
tex += r"""
%% Suggested text for Prop. 5 (C1):
The reversal window is short and the effect is small. Rational certificates at $t=10.46$, $10.47$ and $10.48$ give the signs $-,+,-$ for $\TV(p_3(t),\pi)-\TV(p_4(t),\pi)$, so both crossings lie in explicit rational brackets, $t_1\in(10.46,10.47)$ and $t_2\in(10.47,10.48)$. A 60-digit scan locates them at $t_1\approx%s$ and $t_2\approx%s$; the window has length $%s$. The largest reversed difference is $6.02\times10^{-8}$, about $10^{-4}$ of either distance ($\TV\approx6.7\times10^{-4}$ at $t_*$). The initial conventional gap is $9.63\times10^{-3}$. Because $e^{tG}=\Pi+e^{-\eta t}(e^{tB}-\Pi)$, both distances carry the common factor $e^{-\eta t}$. The crossing times and window are therefore exactly independent of $\eta>0$, and the reset only rescales the effect. Under perturbations $w_5\mapsto w_5\pm10^{-6}$ and $w_5\pm10^{-5}$ (relative size up to $1.7\times10^{-4}$), combined with $\eta\mapsto\eta\pm10^{-5}$, every perturbed model keeps a reversal window inside $(%.4f,%.4f)$. Each such model also has a rational certificate of the reversed sign at $t_*$. Cone preservation is unaffected, since the quotient changes only by $-\eta I$. The preparations $\beta=3,4$ are colder than the bath ($\beta_b=1$) and undergo heating. The transformed quotient in Eq.~\eqref{eq:tvH} is Metzler only on the boundary: several off-diagonal entries are exactly zero.
""" % (s['crossings'][0][:9], s['crossings'][1][:9], s['window_length'][:7], wmin, wmax)
(H/'c1_prop5_table.tex').write_text(tex)
print(tex)
